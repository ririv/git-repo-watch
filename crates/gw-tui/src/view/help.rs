pub(super) const HELP: &str = r#"常驻输入框
直接打字搜索仓库；文件面板中搜索文件。
输入 / 显示命令候选，不需要先激活输入框。
命令候选以小浮层显示，仓库列表与输入框位置保持稳定。
搜索时 ↑↓ 操作列表，Enter 查看选中仓库或文件差异。
命令时 ↑↓ 选择候选，Tab 补全，Enter 执行完整命令。
Esc 清空输入；输入为空时 Esc 返回上一页。
Ctrl+U 清空光标前的文字，Ctrl+A/E 跳到开头或末尾。
文件面板中 Ctrl+A 用于全选当前可见文件。

仓库导航
↑↓ 选择，PgUp/PgDn 翻页；Tab 切换仓库和设置。
Ctrl+F 循环切换全部、问题、无上游、推送。
Alt+O 切换问题优先和路径顺序；F1 打开帮助。
Ctrl+R 刷新当前视图；Ctrl+C 退出。
普通字母、数字和空格用于输入，不触发单字母快捷操作。

命令
/stage 打开工作区，/unstage 打开暂存区。
文件面板：空输入时 Space 勾选，Insert 始终勾选，Ctrl+A 全选可见项。
Tab 切换区域，Enter 查看 diff；筛选隐藏文件时保留已勾选项。
在文件面板执行 /stage 或 /unstage 操作勾选项；未勾选时操作光标项。
取消暂存保留工作区内容；Git 忽略的文件不列出。
/commit 预览暂存内容，输入说明并确认；保留 Git 钩子和签名。
/push 获取当前远程并核验上游，确认后仅推送当前分支快照。
/check all 确认后检查全部注册仓库，按当前策略自动推送。
/refresh 刷新报告或文件列表，/settings 设置，/help 帮助，/quit 退出。
/add、/remove、/exclude、/unexclude 管理注册列表。
/scan 扫描预览，/import 扫描并导入，遵守 Git 忽略规则。
/interval、/autopush、/concurrency、/apply 管理配置与系统调度。
命令范围在输入前缀 / 时固定，命令栏不执行 Shell。

操作确认
配置、检查、提交和推送经 y 确认，n/Esc 取消。
提交说明和配置输入会使用底部输入框，确认或执行期间禁止普通输入。
耗时操作 Esc/Ctrl+C 取消，等待线程与 Git 子进程收尾。
进入界面不会检查、扫描或推送；退出恢复终端。

状态图例
✓ 正常，! 需关注，× 检查失败，· 未检查。
工作区 *改动 包括未提交、未跟踪和子模块改动。
列表来自上次报告；文件面板为显式读取的当前状态。
无上游分支单独统计，不作为问题，也不会自动发布。
↑n !m 是上次检查成功、失败的分支数，? 表示该项未知。
完整失败原因在预览和详情中查看，手动操作不改写历史检查报告。
"#;
